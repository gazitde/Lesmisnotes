const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const base = process.env.SEARCH_TEST_URL || 'http://127.0.0.1:8896';
const externalServer = Boolean(process.env.SEARCH_TEST_URL);
const server = externalServer ? null : spawn(process.execPath, ['scripts/serve.mjs'], { env: { ...process.env, PORT: '8896', CONTACT_ENABLED: 'false' }, stdio: 'ignore' });
let browser, checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; };
(async () => {
  for (let attempt = 0; attempt < 80; attempt++) { try { if ((await fetch(base + '/en/home/')).ok) break; } catch {} await new Promise(resolve => setTimeout(resolve, 100)); }
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  for (const lang of ['en', 'he']) {
    const context = await browser.newContext({ viewport: { width: 1365, height: 900 }, reducedMotion: 'reduce' });
    await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
    const page = await context.newPage(), errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    const openSearch = async query => {
      await page.locator('[data-site-search-open]').click();
      await page.locator('#site-search-input').fill(query);
      await page.waitForTimeout(200);
    };
    await page.goto(base + `/${lang}/home/`);
    await page.locator('[data-action="privacy-reject"]').first().click();
    await openSearch(lang === 'he' ? 'אדון הבית' : 'Master of the House');
    check(await page.locator('.site-search-list a').first().getAttribute('href') === `/${lang}/musical-journey/?focus=song%3Amaster-house`, 'Safe title selects the canonical song entry');
    const result = await page.locator('.site-search-list').innerText();
    check(result.includes(lang === 'he' ? 'התאמה בשם' : 'Name match'), 'Safe result explains title-only match');
    await page.locator('.site-search-list a').first().click();
    check(new URL(page.url()).searchParams.get('focus') === 'song:master-house', 'Song search retains requested ID');
    check(await page.locator('#musical-journey').evaluate(el => document.activeElement === el), 'Non-spotlight safe song focuses the journey gate');
    check((await page.locator('.show-gate .journey-entry-choice h2').innerText()).includes(lang === 'he' ? 'אדון הבית' : 'Master of the House'), 'Gate names requested safe song');
    check(await page.locator('#show-current-title').count() === 0 && await page.locator('.show-slide').count() === 0, 'Search cannot reveal scene text or journey');
    await page.locator('[data-action="language"]').click();
    check(new URL(page.url()).searchParams.get('focus') === 'song:master-house', 'Language change retains requested song');
    check(await page.locator('.show-gate').count() === 1, 'Language switch keeps consent gate');
    await page.reload();
    check(new URL(page.url()).searchParams.get('focus') === 'song:master-house' && await page.locator('.show-gate').count() === 1, 'Reload preserves target and gate');
    await page.locator('[data-action="show-open"]').click();
    check((await page.locator('#show-current-title').innerText()).includes(lang === 'en' ? 'אדון הבית' : 'Master of the House'), 'Explicit reveal opens the exact requested current song');
    await page.locator('[data-action="spoilers"]').click();
    check(await page.locator('#show-current-title').count() === 0 && await page.locator('.show-gate').count() === 1, 'Revocation removes scene content');
    await page.goto(base + `/${lang}/home/`);
    await openSearch('Stars');
    await page.locator('.site-search-list a[href$="focus=song%3Astars"]').click();
    check(await page.locator('#spotlight-title').innerText() === 'Stars', 'Existing featured-song route preserved');
    check(await page.locator('#spotlight-title').evaluate(el => document.activeElement === el), 'Existing safe spotlight focus preserved');
    await page.goto(base + `/${lang}/home/`);
    await openSearch(lang === 'he' ? 'חלק 1 ספר 1 פרק 2' : 'part 1 book 1 chapter 2');
    check(await page.locator('.site-search-list a').count() === 1, 'Coordinate has one exact result');
    await page.locator('.site-search-list a').click();
    await page.locator('#reading-book-panel[data-reader-ready="true"]').waitFor();
    check(new URL(page.url()).searchParams.get('focus') === 'chapter:p1-b1-c2', 'Exact coordinate navigation');
    check(await page.locator('#reading-chapter').inputValue() === 'p1-b1-c2', 'Reader selects current actual chapter');
    check(await page.locator('.chapter-summary-text').count() === 1 && await page.locator('#reader-chapter-p1-b1-c2').evaluate(e => document.activeElement === e), 'Focused reading shows only the requested chapter and focuses it');
    const chapter = JSON.parse(fs.readFileSync('dist/reading/part-1.json')).chapters.find(c => c.id === 'p1-b1-c2');
    check(await page.locator('#reader-chapter-p1-b1-c2 .chapter-summary-text').innerText() === chapter.summary[lang], 'Exact selected summary appears at the search destination');
    check(await page.locator('[data-chapter-reveal]').count() === 0 && await page.locator('[data-novel-event]').count() === 0, 'No redundant reveal button or whole-novel disclosure');
    await page.goBack();
    check(new URL(page.url()).pathname === `/${lang}/home/`, 'Back restores original page');
    await page.goForward();
    await page.locator('#reading-book-panel[data-reader-ready="true"]').waitFor();
    check(await page.locator('#reading-chapter').inputValue() === 'p1-b1-c2' && await page.locator('#reader-chapter-p1-b1-c2 .chapter-summary-text').innerText() === chapter.summary[lang], 'Forward restores exact coordinate and selected summary');
    await openSearch('1.1.999');
    check(await page.locator('.site-search-list a').count() === 0, 'Invalid numeric coordinate has honest empty state');
    await page.locator('#site-search-input').fill('Cossette'); await page.waitForTimeout(200);
    check((await page.locator('.site-search-list a').first().getAttribute('href'))===`/${lang}/character-cosette/`, 'Bounded typo ranks Cosette first');
    await page.keyboard.press('Escape');
    await page.goto(base + `/${lang}/about/`);
    const finder = page.locator('[data-source-search]');
    await finder.fill('gutenberg');
    const before = await page.locator('#source-results').innerText();
    check(before.toLowerCase().includes('gutenberg'), 'Separate source finder still returns source records');
    await openSearch('1.1.2');
    check(await page.locator('.site-search-list a').count() === 1, 'Local chapter search while source filter active');
    await page.keyboard.press('Escape');
    check(await finder.inputValue() === 'gutenberg' && await page.locator('#source-results').innerText() === before, 'Local site search leaves source results and query unchanged');
    check(!requests.some(url => /Cossette|1\.1\.999|part%201%20book|Master%20of%20the%20House/.test(url)), 'Free-text search queries never enter network requests');
    check(!(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).match(/Cossette|1\.1\.999|Master of the House|part 1 book/), 'Free-text queries never stored');
    check(errors.length === 0, 'No browser runtime errors: ' + errors.join('; '));
    await context.close();
  }
  console.log(`Search polish browser: ${checks} checks passed; Hebrew/English title-only navigation, exact chapter selection, source results, consent, language, reload and history.`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server?.kill(); });
