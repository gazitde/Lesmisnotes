import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { performance } from 'node:perf_hooks';
const ctx={window:{},URLSearchParams};vm.createContext(ctx);
for(const file of ['research','extras','places-data','recipes-data','seo','search'])vm.runInContext(fs.readFileSync(`dist/${file}.js`,'utf8'),ctx);
const W=ctx.window,S=W.SiteSearch,source={research:W.RESEARCH,extra:W.EXTRA_CONTENT,places:W.PLACE_CONTENT,recipes:W.RECIPE_CONTENT,metadata:W.SITE_METADATA};
const safe=S.buildIndex(source,{spoiler:false}),on=S.buildIndex(source,{spoiler:true}),all=S.buildIndex(source,{spoiler:true,novelConsent:true});
let checks=0;const check=(value,label)=>{assert.ok(value,label);checks++};
const find=(index,q,lang='en',category='all')=>S.search(index,q,{lang,category,limit:500});
const ids=(index,q,lang='en',category='all')=>find(index,q,lang,category).results.map(x=>x.doc.id);
check(safe.length>80,'Meaningful source-derived safe index');
check(all.length>on.length&&on.length>safe.length,'Independent spoiler permission partitions');
for(const q of ['Valjean','Jean Valjean','24601',"ז'אן ולז'אן",'זָ׳אן וַלְזָ׳אן'])check(find(safe,q).results[0]?.doc.id==='character:valjean','Valjean bilingual alias '+q);
check(S.normalize('Éponine – תֵּנַרְדְּיֵה')==='eponine תנרדיה','Accents and niqqud normalized');
check(ids(safe,'Eponine').includes('character:eponine'),'Accent-free French name');
check(ids(safe,'Thenardier').includes('character:thenardiers'),'English singular alias');
check(ids(safe,'טנארדייה','he').includes('character:thenardiers'),'Hebrew alternate transliteration');
check(ids(safe,'dockyards').includes('atlas:toulon'),'Place body beyond title');
check(ids(safe,'מספנות','he').includes('atlas:toulon'),'Hebrew place body beyond title');
check(ids(safe,'Haussmann').includes('place:luxembourg'),'Historical essay full text');
check(ids(safe,'cholera').includes('history:1832'),'History body beyond title');
check(ids(safe,'כולרה','he').includes('history:1832'),'Hebrew history body beyond title');
check(ids(safe,'sesame').includes('recipe:tahini-walnut-loaf'),'Ingredient/allergen search');
check(ids(safe,'שומשום','he').includes('recipe:tahini-walnut-loaf'),'Hebrew ingredient search');
check(ids(safe,'yellow passport').includes('dilemma:law-mercy'),'Dilemma argument body search');
check(ids(safe,'דרכון צהוב','he').includes('dilemma:law-mercy'),'Hebrew dilemma body search');
check(ids(safe,'Lucy Thomas').some(x=>x.startsWith('performance:')),'Performance search');
check(ids(safe,'24601','en','recipes').length===0,'Topic filter applies');
check(find(safe,'    ').total===0,'Whitespace empty state');
check(find(safe,'<img src=x onerror=alert(1)>').total===0,'Arbitrary query safely unmatched');
check(S.highlight('<img onerror="x">&Éponine','Eponine')==='&lt;img onerror=&quot;x&quot;&gt;&amp;<mark>Éponine</mark>','Escaping precedes highlighting');
check(S.highlight('זָ׳אן וַלְזָ׳אן',"ולז'אן").includes('<mark>וַלְזָ׳אן</mark>'),'Hebrew normalization preserves original display offsets');
check(!JSON.stringify(safe.find(x=>x.id==='character:valjean')).includes('9430'),'Locked character body absent from index');
check(!ids(safe,'9430').includes('character:valjean'),'Hidden content not used for matching');
check(ids(on,'9430').includes('character:valjean'),'Character depth available after explicit opt-in');
check(ids(on,'Combeferre').includes('character:enjolras'),'New novel close reading is searchable after consent');
check(!ids(safe,'Combeferre').includes('character:enjolras'),'New character note cannot leak through safe search');
check(ids(on,'קומבפר','he').includes('character:enjolras'),'New Hebrew close reading is searchable');
check(ids(safe,'Matt Kinley').includes('craft:hugo-art-onstage'),'Spoiler-safe production design note is searchable');
check(S.readTarget('?focus=craft%3Ahugo-art-onstage','musical')?.key==='hugo-art-onstage','Craft note has a localized safe deep link');

check(!safe.some(x=>x.kind==='story'||x.kind==='novel'),'Hidden story and novel titles absent');
check(!on.some(x=>x.kind==='novel'),'General spoiler setting does not bypass separate novel consent');
check(all.some(x=>x.kind==='novel'),'Explicit novel consent opens novel index');
check(!safe.some(x=>x.id==='history:1848'),'Gated later history absent');
check(on.some(x=>x.id==='history:1848'),'Gated later history available after consent');
// Canary fields prove hidden fields never influence counts, ranking or snippets.
const probe=structuredClone(source);
probe.research.characters[0].summary={he:'סודסודסוד',en:'HIDDENCHARACTERCANARY'};
probe.extra.musical.spotlight.songs[0].plot={he:'סודהשיר',en:'HIDDENSONGCANARY'};
probe.places.places[0].novel={he:'סודהמקום',en:'HIDDENPLACECANARY'};
probe.extra.novel.milestones[0].summary={he:'סודהספר',en:'HIDDENNOVELCANARY'};
probe.extra.gallery.groups.find(g=>g.id==='stars-pair').reading={title:{he:'סודהקריאה',en:'HIDDENREADINGCANARY'},spoilerLevel:2};
const protectedIndex=S.buildIndex(probe,{spoiler:false});
for(const q of ['HIDDENCHARACTERCANARY','HIDDENSONGCANARY','HIDDENPLACECANARY','HIDDENNOVELCANARY','HIDDENREADINGCANARY'])check(find(protectedIndex,q).total===0,'No hidden canary match '+q);
check(find(S.buildIndex(probe,{spoiler:true}),'HIDDENREADINGCANARY').total===2,'Consented reading canary');
check(find(S.buildIndex(probe,{spoiler:true}),'HIDDENNOVELCANARY').total===0,'Separate novel gate canary');
check(find(S.buildIndex(probe,{spoiler:true,novelConsent:true}),'HIDDENNOVELCANARY').total===1,'Consented novel canary');
const doc=safe.find(x=>x.id==='character:valjean');
check(S.hrefFor(doc,'he')==='/he/characters/?focus=character%3Avaljean','Localized direct link');
check(S.readTarget('?focus=character%3Avaljean','characters')?.key==='valjean','Target parsing');
check(S.readTarget('?focus=character%3Avaljean','history')===null,'Target rejects wrong route');
check(S.readTarget('?focus=character%3A%22%3E%3Cimg','characters')===null,'Target rejects selector injection');
check(S.resultsHTML(find(safe,'24601'),'24601','he').includes('/he/characters/'),'Result does not change chosen language');
const changed=structuredClone(source);changed.recipes.recipes[0].ingredients.en.push('SOURCECHANGECANARY');
check(ids(S.buildIndex(changed),'SOURCECHANGECANARY').includes('recipe:bishops-bread-soup'),'Index reflects source edits without duplicated corpus');
check(S.buildIndex({}).length===0,'Empty/offline missing index supported');
const t=performance.now();for(let i=0;i<100;i++)find(all,i%2?'Valjean':'מרק','en');const duration=performance.now()-t;
check(duration<1500,`100 searches complete promptly (${Math.round(duration)} ms)`);
const text=fs.readFileSync('dist/search.js','utf8');
check(!/\b(?:fetch|XMLHttpRequest|sendBeacon|localStorage|sessionStorage|gtag)\s*[.(]/.test(text),'Search has no network/storage/analytics APIs');
console.log(`Search: ${checks} checks passed; ${safe.length} safe / ${on.length} spoiler / ${all.length} novel-consented records; 100 searches in ${Math.round(duration)} ms.`);
